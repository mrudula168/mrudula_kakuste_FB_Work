### Numeric  -  category
#1. int
var = 10

#2. float
var = 3.14

#3. complex
var = 10 + 5j #real + imaginary

### Text  -  category
#1. str
var = 'First"bit" Solutions'
var = "Firstbit's Solutions"
var = '''
This is first line.
This is second line.
'''
"""
This is first line.
This is second line.
"""


### Sequential
#1. list
var = [10, 20, 30]

#2. tuple
var = (10, 20, 30)

#3. range
var = range(1, 10)



### Set type
#1. set
var = {10, 20, 30, 40}

#2. frozenset
var = frozenset({10, 20, 30, 40})


### Mapping
#1. dict
var = {1:'Python', 2:'Java', 3:'C'}


### Other
#1. bool
var = True

#2. Nonetype
var = None
print(type(var))
